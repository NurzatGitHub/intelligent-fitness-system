class Command(BaseCommand):
    help = "Seed exercise categories, subcategories and exercises"

    def add_arguments(self, parser):
        parser.add_argument(
            "--reset",
            action="store_true",
            help="Delete all exercise data before seeding",
        )

    @transaction.atomic
    def handle(self, *args, **options):
        reset = options["reset"]

        if reset:
            self.stdout.write(self.style.WARNING("Deleting old exercise data..."))
            Exercise.objects.all().delete()
            ExerciseSubcategory.objects.all().delete()
            ExerciseCategory.objects.all().delete()

        self.stdout.write("Seeding categories...")
        category_map = {}

        for item in CATEGORIES:
            category, _ = ExerciseCategory.objects.update_or_create(
                slug=item["slug"],
                defaults={
                    "name": item["name"],
                    "description": item.get("description", ""),
                    "sort_order": item.get("sort_order", 0),
                    "is_active": True,
                },
            )
            category_map[item["slug"]] = category

        self.stdout.write("Seeding subcategories...")
        subcategory_map = {}

        for item in SUBCATEGORIES:
            category = category_map[item["category_slug"]]
            subcategory, _ = ExerciseSubcategory.objects.update_or_create(
                category=category,
                slug=item["slug"],
                defaults={
                    "name": item["name"],
                    "description": item.get("description", ""),
                    "sort_order": item.get("sort_order", 0),
                    "is_active": True,
                },
            )
            subcategory_map[f'{item["category_slug"]}:{item["slug"]}'] = subcategory

        self.stdout.write("Seeding exercises...")

        created_or_updated = 0

        for item in EXERCISES:
            category = category_map[item["category_slug"]]
            subcategory = subcategory_map[f'{item["category_slug"]}:{item["subcategory_slug"]}']

            instructions_text = "\n".join(item.get("instructions", []))
            tips_text = "\n".join(item.get("tips", []))

            Exercise.objects.update_or_create(
                external_id=item["external_id"],
                defaults={
                    "category": category,
                    "subcategory": subcategory,
                    "name": item["name"],
                    "slug": item["slug"],
                    "description": item.get("description", ""),
                    "target_muscle": item.get("target_muscle", ""),
                    "equipment": item.get("equipment", ""),
                    "difficulty": item.get("difficulty", "beginner"),
                    "instructions": instructions_text,
                    "tips": tips_text,
                    "video_url": item.get("video_url", ""),
                    "asset_image_name": item.get("asset_image_name", ""),
                    "asset_video_name": item.get("asset_video_name", ""),
                    "default_sets": item.get("default_sets"),
                    "default_reps": item.get("default_reps"),
                    "default_duration_min": item.get("default_duration_min"),
                    "is_active": True,
                    "sort_order": item.get("sort_order", 0),
                },
            )
            created_or_updated += 1

        self.stdout.write(self.style.SUCCESS(
            f"Done. Seeded {len(category_map)} categories, "
            f"{len(subcategory_map)} subcategories, "
            f"{created_or_updated} exercises."
        ))